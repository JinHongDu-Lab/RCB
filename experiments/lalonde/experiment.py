def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--plasmode-reps", type=int, default=100)
    parser.add_argument("--data", type=Path, default=DATA_PATH)
    args = parser.parse_args()
    ARTIFACTS.mkdir()

    d = load_lalonde171(args.data)
    real, details = run_exploratory_pipeline(d)
    compute_double_ridge_sweep(d, details["lambda_cv"])
    plas, evaluation_plasmode = run_plasmode(
        d, args.plasmode_reps, return_evaluation=True
    )

    validation = {
        "n_control": len(d["y0"]),
        "n_treated": len(d["yt"]),
        "feature_count": len(d["feature_names"]),
        "centered_source_rank": d["rank"],
        "experimental_benchmark_att": d["benchmark"],
        "treated_outcome_mean": d["ybar_t"],
        "unadjusted_att": d["ybar_t"] - d["y0"].mean(),
        "paper_cv_lambda_normalized": details["lambda_cv"],
        "paper_cv_lambda_raw": details["lambda_cv"] * len(d["y0"]),
        "double_ridge_linear_representation_error": details["double"]["linear_representation_error"],
    }
    (ARTIFACTS / "validation.json").write_text(
        json.dumps(validation, indent=2), encoding="utf-8"
    )
    real.to_csv(ARTIFACTS / "real_data_method_comparison.csv", index=False)
    details["split_df"].to_csv(ARTIFACTS / "split_sensitivity.csv", index=False)
    pd.DataFrame({
        "lambda_normalized": GRID,
        "lambda_raw": GRID * len(d["y0"]),
        "cv_r2": details["cv_r2"],
    }).to_csv(ARTIFACTS / "paper_ridge_cv_curve.csv", index=False)
    plas.to_csv(ARTIFACTS / "known_truth_plasmode_metrics.csv", index=False)
    details["family_comparison"].to_csv(
        ARTIFACTS / "evaluation_style_real_data_comparison.csv", index=False
    )
    evaluation_plasmode.to_csv(
        ARTIFACTS / "evaluation_style_plasmode_metrics.csv", index=False
    )
    write_report(d, real, details, plas, evaluation_plasmode)

    print(json.dumps(validation, indent=2))
    print("\nReal-data comparison")
    print(real[[
        "method", "att", "distance_to_experimental_benchmark",
        "common_plugin_ood_risk_proxy", "ess", "selected_lambda_normalized",
    ]].to_string(index=False))
    print("\nKnown-truth plasmode")
    print(plas[["method", "bias", "sd", "rmse", "rmse_over_oracle"]].to_string(index=False))
    print(f"\nWrote artifacts to {ARTIFACTS}")


if __name__ == "__main__":
    main()
